#!/usr/bin/env bash
# Sets up Azure IoT Hub + Event Grid for JagSi (issue #8).
#
#   infra/azure/deploy.sh hub                 # 1. resource group, IoT hub, device, secrets
#   infra/azure/deploy.sh eventgrid <url>     # 2. route device messages to the backend
#   infra/azure/deploy.sh status              # what exists right now
#   infra/azure/deploy.sh teardown            # delete everything (asks first)
#
# Needs: Azure CLI (`az login` done), openssl, python3. See docs/azure-setup.md.
#
# Everything secret is written to infra/azure/out/ and to
# firmware/jagsi-watch/azure_config.h. Both are in .gitignore. Never commit them.
set -euo pipefail

RG="${JAGSI_RG:-jagsi-rg}"
LOCATION="${JAGSI_LOCATION:-southeastasia}"
HUB="${JAGSI_HUB:-}"
DEVICE="${JAGSI_DEVICE:-jagsi-watch-01}"
# F1 is free but capped at 8,000 messages a day. The watch sends about 1.5 a
# second (one motion window + one telemetry every 2 s), so F1 runs out after
# roughly 1.5 hours. Fine for setting up and demos; use S1 for longer runs.
SKU="${JAGSI_SKU:-F1}"

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/infra/azure/out"
FW_CONFIG="$ROOT/firmware/jagsi-watch/azure_config.h"
STATE="$OUT/state.env"

say() { printf '\n==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

need() { command -v "$1" >/dev/null 2>&1 || die "$1 is not installed"; }

load_state() {
  if [[ -f "$STATE" ]]; then
    # shellcheck disable=SC1090
    source "$STATE"
  fi
  HUB="${HUB:-${SAVED_HUB:-}}"
}

cmd_hub() {
  need az; need openssl; need python3
  az account show >/dev/null 2>&1 || die "run 'az login' first"
  mkdir -p "$OUT"; chmod 700 "$OUT"
  load_state
  if [[ -z "$HUB" ]]; then
    # Hub names are global DNS names, so add a short random suffix.
    HUB="jagsi-abal-$(openssl rand -hex 3)"
  fi
  printf 'SAVED_HUB=%q\n' "$HUB" > "$STATE"

  say "Azure IoT extension"
  az extension add --upgrade --name azure-iot --only-show-errors

  say "Resource group $RG ($LOCATION)"
  az group create --name "$RG" --location "$LOCATION" --only-show-errors -o none

  say "IoT hub $HUB ($SKU)"
  if az iot hub show --name "$HUB" -o none 2>/dev/null; then
    echo "already exists"
  else
    # The free tier only allows 2 partitions.
    az iot hub create --name "$HUB" --resource-group "$RG" --location "$LOCATION" \
      --sku "$SKU" --partition-count 2 --only-show-errors -o none
  fi

  say "Device certificate for $DEVICE (self-signed, EC P-256)"
  KEY="$OUT/$DEVICE.key.pem"
  CERT="$OUT/$DEVICE.cert.pem"
  if [[ ! -f "$KEY" ]]; then
    ( umask 077; openssl ecparam -name prime256v1 -genkey -noout -out "$KEY" )
    openssl req -new -x509 -key "$KEY" -subj "/CN=$DEVICE" -days 365 -sha256 -out "$CERT"
  else
    echo "reusing $KEY"
  fi
  # IoT Hub matches a self-signed device by certificate thumbprint.
  THUMB="$(openssl x509 -in "$CERT" -noout -fingerprint -sha1 | cut -d= -f2 | tr -d ':')"
  echo "thumbprint $THUMB"

  say "Device identity $DEVICE"
  # Re-created rather than updated, so a re-run always ends with exactly this
  # certificate registered. The identity holds no data worth keeping.
  if az iot hub device-identity show --hub-name "$HUB" --device-id "$DEVICE" -o none 2>/dev/null; then
    az iot hub device-identity delete --hub-name "$HUB" --device-id "$DEVICE" -o none
  fi
  az iot hub device-identity create --hub-name "$HUB" --device-id "$DEVICE" \
    --auth-method x509_thumbprint --primary-thumbprint "$THUMB" --secondary-thumbprint "$THUMB" -o none

  say "Backend secrets"
  HUB_HOST="$(az iot hub show --name "$HUB" --query properties.hostName -o tsv)"
  # 'service' has ServiceConnect only: enough to invoke direct methods, not
  # enough to create or delete devices.
  POLICY_KEY="$(az iot hub policy show --hub-name "$HUB" --name service --query primaryKey -o tsv)"
  EG_KEY_FILE="$OUT/eventgrid.key"
  [[ -f "$EG_KEY_FILE" ]] || ( umask 077; openssl rand -hex 24 > "$EG_KEY_FILE" )
  ( umask 077; cat > "$OUT/backend.env" <<ENV
# Generated by infra/azure/deploy.sh. Load before starting the backend:
#   set -a; source ../infra/azure/out/backend.env; set +a
JAGSI_INGEST=azure
JAGSI_IOTHUB_HOSTNAME=$HUB_HOST
JAGSI_IOTHUB_POLICY=service
JAGSI_IOTHUB_POLICY_KEY=$POLICY_KEY
JAGSI_EVENTGRID_KEY=$(cat "$EG_KEY_FILE")
ENV
  )
  echo "wrote $OUT/backend.env"

  say "Firmware config"
  python3 - "$HUB_HOST" "$CERT" "$KEY" "$FW_CONFIG" <<'PY'
import sys
host, cert, key, out = sys.argv[1:]
def c_string(path):
    return "\n".join(f'"{line}\\n"' for line in open(path).read().strip().splitlines())
with open(out, "w") as f:
    f.write(f"""// GENERATED by infra/azure/deploy.sh. Holds the device PRIVATE KEY.
// In .gitignore: never commit it, never paste it into a public Wokwi project.
#pragma once

#define JAGSI_AZURE 1
#define AZURE_IOTHUB_HOST "{host}"

static const char AZURE_DEVICE_CERT[] =
{c_string(cert)};

static const char AZURE_DEVICE_KEY[] =
{c_string(key)};
""")
PY
  chmod 600 "$FW_CONFIG"
  echo "wrote $FW_CONFIG"

  cat <<NEXT

IoT hub ready: $HUB_HOST, device $DEVICE.

Next:
  1. Start the backend in azure mode (from backend/):
       set -a; source ../infra/azure/out/backend.env; set +a
       uvicorn app.main:app --port 8000
  2. Give it a public HTTPS URL, for example:
       devtunnel host -p 8000 --allow-anonymous     (or: ngrok http 8000)
  3. infra/azure/deploy.sh eventgrid https://<that-url>
  4. Put azure_config.h next to sketch.ino (Wokwi: add a file with that name,
     in a PRIVATE project) and run the watch.
NEXT
}

cmd_eventgrid() {
  need az
  local url="${1:-}"
  [[ "$url" == https://* ]] || die "usage: deploy.sh eventgrid https://<public backend url>"
  url="${url%/}"
  load_state
  [[ -n "$HUB" ]] || die "no hub yet, run 'deploy.sh hub' first"
  local key; key="$(cat "$OUT/eventgrid.key")"

  say "Event Grid resource provider"
  az provider register --namespace Microsoft.EventGrid --wait

  say "Checking the backend answers before creating the subscription"
  # Event Grid validates the endpoint while the subscription is created, so the
  # backend must already be running in azure mode behind this URL.
  if command -v curl >/dev/null; then
    code="$(curl -s -o /dev/null -w '%{http_code}' -X POST "$url/api/ingest/eventgrid?key=$key" \
      -H 'Content-Type: application/json' -d '[]' || true)"
    [[ "$code" == "200" ]] || die "backend answered HTTP $code at $url/api/ingest/eventgrid (expected 200; is JAGSI_INGEST=azure loaded?)"
  fi

  say "Event subscription jagsi-backend -> $url/api/ingest/eventgrid"
  HUB_ID="$(az iot hub show --name "$HUB" --query id -o tsv)"
  az eventgrid event-subscription create \
    --name jagsi-backend \
    --source-resource-id "$HUB_ID" \
    --endpoint-type webhook \
    --endpoint "$url/api/ingest/eventgrid?key=$key" \
    --included-event-types Microsoft.Devices.DeviceTelemetry Microsoft.Devices.DeviceConnected Microsoft.Devices.DeviceDisconnected \
    --max-delivery-attempts 3 --event-ttl 5 \
    --only-show-errors -o none
  echo "done. Device messages now reach the backend through Event Grid."
}

cmd_status() {
  need az
  load_state
  [[ -n "$HUB" ]] || die "no hub recorded in $STATE"
  az iot hub show --name "$HUB" --query "{name:name, host:properties.hostName, sku:sku.name, state:properties.state}" -o table
  az iot hub device-identity list --hub-name "$HUB" --query "[].{device:deviceId, auth:authentication.type, state:connectionState}" -o table
  HUB_ID="$(az iot hub show --name "$HUB" --query id -o tsv)"
  az eventgrid event-subscription list --source-resource-id "$HUB_ID" --query "[].{name:name, state:provisioningState}" -o table || true
}

cmd_teardown() {
  need az
  read -r -p "Delete resource group $RG and everything in it? Type the name to confirm: " answer
  [[ "$answer" == "$RG" ]] || die "not confirmed"
  az group delete --name "$RG" --yes --no-wait
  echo "deletion started. Local secrets in $OUT and $FW_CONFIG were kept; delete them yourself."
}

case "${1:-}" in
  hub) cmd_hub ;;
  eventgrid) shift; cmd_eventgrid "${1:-}" ;;
  status) cmd_status ;;
  teardown) cmd_teardown ;;
  *) sed -n '2,10p' "$0"; exit 1 ;;
esac
